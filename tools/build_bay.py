#!/usr/bin/env python3
"""Builds game/bay_data.gd: the coastline of Port Phillip Bay for the game.

Source: Natural Earth 1:10m land polygons (public domain, naturalearthdata.com).
Download ne_10m_land.geojson from
https://github.com/nvkelso/natural-earth-vector/tree/master/geojson and run:

    pip install shapely mapbox-earcut numpy
    python3 tools/build_bay.py path/to/ne_10m_land.geojson game/bay_data.gd

The coast is clipped to the bay, projected to game pixels (400 px = 1 nautical
mile, north up), rounded off a little, and cut into triangles for drawing.
"""
import json
import math
import sys

import mapbox_earcut
import numpy as np
from shapely.geometry import Point, Polygon, box, shape
from shapely.ops import nearest_points, unary_union

WEST, SOUTH, EAST, NORTH = 144.30, -38.42, 145.20, -37.78
PX_PER_NM = 400.0
LON_SCALE = math.cos(math.radians((SOUTH + NORTH) / 2.0))
# Ports sit this far (px) off the coast so there is room to dock.
PORT_CLEARANCE = 260.0

# Approximate real positions; each is moved to the nearest water with clearance.
PORTS = {
    "melbourne": (144.91, -37.88),
    "geelong": (144.39, -38.13),
    "queenscliff": (144.68, -38.25),
    "mornington": (145.02, -38.21),
}


def to_px(lon, lat):
    return ((lon - WEST) * LON_SCALE * 60.0 * PX_PER_NM, (NORTH - lat) * 60.0 * PX_PER_NM)


WIDTH, HEIGHT = to_px(EAST, SOUTH)


def on_edge(p):
    return min(abs(p[0]), abs(p[0] - WIDTH), abs(p[1]), abs(p[1] - HEIGHT)) < 0.5


def chaikin(ring):
    """Rounds corners, leaving points on the map edge where they are."""
    out = []
    count = len(ring)
    for i in range(count):
        a, b = ring[i], ring[(i + 1) % count]
        if on_edge(a):
            out.append(a)
        else:
            out.append((0.75 * a[0] + 0.25 * b[0], 0.75 * a[1] + 0.25 * b[1]))
        if not on_edge(b):
            out.append((0.25 * a[0] + 0.75 * b[0], 0.25 * a[1] + 0.75 * b[1]))
    return out


def polygons(geometry):
    if geometry.geom_type == "Polygon":
        return [geometry]
    return [g for g in getattr(geometry, "geoms", []) if g.geom_type == "Polygon"]


def main(source, target):
    world = box(0.0, 0.0, WIDTH, HEIGHT)
    lonlat_box = box(WEST, SOUTH, EAST, NORTH)
    pieces = []
    for feature in json.load(open(source))["features"]:
        land = shape(feature["geometry"])
        if land.intersects(lonlat_box):
            for polygon in polygons(land.intersection(lonlat_box)):
                ring = [to_px(lon, lat) for lon, lat in polygon.exterior.coords[:-1]]
                for _ in range(2):
                    ring = chaikin(ring)
                pieces.append(Polygon(ring).buffer(0))
    land = unary_union(pieces).intersection(world).simplify(6.0)
    rings = []
    triangles = []
    for polygon in polygons(land):
        if polygon.area < 2000.0:
            continue
        if polygon.interiors:
            raise SystemExit("land polygon has holes: not supported")
        ring = [(round(x), round(y)) for x, y in polygon.exterior.coords[:-1]]
        rings.append(ring)
        vertices = np.array(ring, dtype=np.float64)
        indices = mapbox_earcut.triangulate_float64(vertices, np.array([len(ring)], dtype=np.uint32))
        triangles.extend(ring[i] for i in indices)

    water = world.difference(land)
    ports = {}
    for name, (lon, lat) in PORTS.items():
        wanted = Point(to_px(lon, lat))
        roomy = water.buffer(-PORT_CLEARANCE)
        # Stay in the main bay: the roomy water nearest the wanted position.
        spot = nearest_points(roomy, wanted)[0]
        ports[name] = (round(spot.x), round(spot.y))

    def vectors(points):
        return ", ".join("Vector2(%d, %d)" % p for p in points)

    lines = [
        "extends RefCounted",
        "## Generated by tools/build_bay.py: do not edit by hand.",
        "## Port Phillip Bay coastline from Natural Earth 1:10m (public domain).",
        "",
        "const SIZE := Vector2(%d, %d)" % (round(WIDTH), round(HEIGHT)),
        "const WEST := %.4f" % WEST,
        "const NORTH := %.4f" % NORTH,
        "const PX_PER_DEGREE_LON := %.4f" % (LON_SCALE * 60.0 * PX_PER_NM),
        "const PX_PER_DEGREE_LAT := %.4f" % (60.0 * PX_PER_NM),
        "",
        "const PORT_POSITIONS := {",
    ]
    for name, spot in ports.items():
        lines.append('\t"%s": Vector2(%d, %d),' % (name, spot[0], spot[1]))
    lines += ["}", "", "## Coastline outlines, one closed ring per piece of land.", "const LAND_RINGS := ["]
    for ring in rings:
        lines.append("\t[%s]," % vectors(ring))
    lines += ["]", "", "## The same land cut into triangles: three points each.", "const LAND_TRIANGLES := ["]
    for i in range(0, len(triangles), 30):
        lines.append("\t%s," % vectors(triangles[i:i + 30]))
    lines += ["]", ""]
    open(target, "w").write("\n".join(lines))
    print("size", round(WIDTH), round(HEIGHT), "rings", [len(r) for r in rings], "triangles", len(triangles) // 3, "ports", ports)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
